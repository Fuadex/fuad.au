// fetch-subjects.js — what a work DEPICTS and what GENRE it is, from Wikidata.
//
// The site can search titles, artists and museums. It cannot answer "show me the sea", because
// nothing in the data describes subject matter. This is the free, structured half of fixing that:
//
//   P180  depicts  — entities actually shown in the picture (dog, sea, Paris, Venus)
//   P136  genre    — landscape / portrait / still life / seascape / history painting
//
// Both are keyless and batched 45 qids per call. Coverage is expected to be patchy — that is the
// point of running it before committing to anything expensive: it tells us how far free data gets
// us, and only then whether a vision pass is worth it.
//
//   node fetch-subjects.js        (resumable; cache in subjects_cache.json)
const fs = require("fs"), path = require("path");
const HERE = __dirname;
const UA = { "User-Agent": "fuad.au-canvas/0.1 (https://fuad.au; fuadex@gmail.com)" };
const CACHE = path.join(HERE, "subjects_cache.json");     // work qid -> { d:[qids], g:[qids] }
const LABELS = path.join(HERE, "subjects_labels.json");   // entity qid -> English label
const load = (f, fb) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch (e) { return fb; } };
const cache = load(CACHE, {}), labels = load(LABELS, {});

const g = {};
new Function("window", fs.readFileSync(path.join(HERE, "artworks.js"), "utf8") + "\nreturn window;")(g);
const WORKS = g.CANVAS_ARTWORKS.filter(w => w.qid && /^Q\d+$/.test(w.qid));
const todo = [...new Set(WORKS.map(w => w.qid))].filter(q => !(q in cache));
console.log(`${WORKS.length} works with a real qid · ${todo.length} to fetch · ${Object.keys(cache).length} cached`);

const sleep = (ms) => new Promise(r => setTimeout(r, ms));
async function api(url) {
  for (let a = 0; a < 6; a++) {
    const res = await fetch(url, { headers: UA });
    const body = await res.text();
    await sleep(300);
    if (res.ok && body[0] === "{") { try { return JSON.parse(body); } catch (e) {} }
    const wait = 2000 * Math.pow(2, a);
    console.log(`  ⏳ ${res.status} — backing off ${wait / 1000}s`);
    await sleep(wait);
  }
  return null;
}
const claimIds = (ent, p) => ((ent && ent.claims && ent.claims[p]) || [])
  .map(c => c.mainsnak && c.mainsnak.datavalue && c.mainsnak.datavalue.value)
  .filter(v => v && v.id).map(v => v.id);

(async () => {
  for (let i = 0; i < todo.length; i += 45) {
    const batch = todo.slice(i, i + 45);
    const j = await api("https://www.wikidata.org/w/api.php?action=wbgetentities&props=claims&format=json&ids=" + batch.join("|"));
    for (const q of batch) {
      const e = j && j.entities && j.entities[q];
      cache[q] = { d: claimIds(e, "P180"), g: claimIds(e, "P136") };
    }
    fs.writeFileSync(CACHE, JSON.stringify(cache));
    if (i % 450 === 0) console.log(`  ${Math.min(i + 45, todo.length)}/${todo.length}`);
  }

  // labels for every distinct depicted/genre entity
  const need = [...new Set(Object.values(cache).flatMap(v => [...v.d, ...v.g]))].filter(q => !(q in labels));
  console.log(`resolving ${need.length} subject labels`);
  for (let i = 0; i < need.length; i += 45) {
    const batch = need.slice(i, i + 45);
    const j = await api("https://www.wikidata.org/w/api.php?action=wbgetentities&props=labels&languages=en&format=json&ids=" + batch.join("|"));
    for (const q of batch) {
      const e = j && j.entities && j.entities[q];
      labels[q] = (e && e.labels && e.labels.en && e.labels.en.value) || null;
    }
    fs.writeFileSync(LABELS, JSON.stringify(labels, null, 1));
    if (i % 450 === 0) console.log(`  labels ${Math.min(i + 45, need.length)}/${need.length}`);
  }

  const out = {};
  let withD = 0, withG = 0;
  for (const w of WORKS) {
    const c = cache[w.qid]; if (!c) continue;
    const d = c.d.map(q => labels[q]).filter(Boolean);
    const gg = c.g.map(q => labels[q]).filter(Boolean);
    if (!d.length && !gg.length) continue;
    if (d.length) withD++;
    if (gg.length) withG++;
    out[w.id] = gg.length ? { d, g: gg } : { d };
  }
  fs.writeFileSync(path.join(HERE, "art_subjects.js"),
    "// GENERATED by fetch-subjects.js — Wikidata subject data per work.\n" +
    "//   d = depicts (P180), the things actually shown; g = genre (P136).\n" +
    "// Coverage is uneven by nature: famous works are described, most are not.\n" +
    "window.CANVAS_SUBJECTS = " + JSON.stringify(out) + ";\n", "utf8");

  console.log(`\nworks with ANY subject data: ${Object.keys(out).length} of ${WORKS.length} (${Math.round(Object.keys(out).length / WORKS.length * 100)}%)`);
  console.log(`  with depicts: ${withD}   with genre: ${withG}`);
  const dTally = {}, gTally = {};
  for (const v of Object.values(out)) {
    for (const x of v.d || []) dTally[x] = (dTally[x] || 0) + 1;
    for (const x of v.g || []) gTally[x] = (gTally[x] || 0) + 1;
  }
  console.log(`\ntop genres:\n` + Object.entries(gTally).sort((a, b) => b[1] - a[1]).slice(0, 14).map(([k, n]) => `  ${String(n).padStart(4)}  ${k}`).join("\n"));
  console.log(`\ntop depicted subjects:\n` + Object.entries(dTally).sort((a, b) => b[1] - a[1]).slice(0, 25).map(([k, n]) => `  ${String(n).padStart(4)}  ${k}`).join("\n"));
})();
